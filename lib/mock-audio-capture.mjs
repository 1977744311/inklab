// 0.18+ getUserMedia bypasses hostCapabilities. Supply an inert browser audio
// track; the mock media provider supplies WAV chunks and ASR text is injected.
// Never request a real microphone merely to run an ASR simulation.
export function installMockAudioCapture({
  navigatorRef = globalThis.navigator,
  MediaStreamCtor = globalThis.MediaStream,
  TrackGenerator = globalThis.MediaStreamTrackGenerator,
  AudioContextCtor = globalThis.AudioContext || globalThis.webkitAudioContext,
} = {}) {
  const devices = navigatorRef?.mediaDevices;
  if (!devices || typeof devices.getUserMedia !== 'function') return { installed: false, dispose() {} };
  const original = devices.getUserMedia;
  const descriptor = Object.getOwnPropertyDescriptor(devices, 'getUserMedia');
  const owned = new Map();
  let disposed = false;
  const mock = async constraints => {
    if (disposed) throw new Error('Mock audio capture is disposed');
    if (!constraints?.audio) return original.call(devices, constraints);
    if (constraints.video) throw new DOMException('Mock microphone only supports audio-only capture', 'NotSupportedError');
    let stream, context = null;
    if (typeof TrackGenerator === 'function' && typeof MediaStreamCtor === 'function') {
      stream = new MediaStreamCtor([new TrackGenerator({ kind: 'audio' })]);
    } else if (typeof AudioContextCtor === 'function') {
      context = new AudioContextCtor();
      stream = context.createMediaStreamDestination().stream;
      // Do not resume/connect to speakers. Only the live track is needed; WAV
      // data is generated by the capability mock without autoplay permission.
    } else throw new DOMException('No simulated audio track backend is available', 'NotSupportedError');
    for (const track of stream.getTracks()) {
      const stop = track.stop.bind(track);
      const release = () => { stop(); owned.delete(track); context?.close?.()?.catch?.(() => {}); };
      owned.set(track, release);
      track.stop = release;
    }
    return stream;
  };
  Object.defineProperty(devices, 'getUserMedia', { configurable: true, writable: true, value: mock });
  return {
    installed: true,
    dispose() {
      if (disposed) return;
      disposed = true;
      for (const release of [...owned.values()]) release();
      if (devices.getUserMedia === mock) {
        if (descriptor) Object.defineProperty(devices, 'getUserMedia', descriptor);
        else delete devices.getUserMedia;
      }
    },
  };
}
